"""Writes each service's checked-in HTML reference, `{service}/v1/reference.html`.

The page embeds the service's AsyncAPI document as one self-contained JSON
object and renders it in the browser with the AsyncAPI React component (the
renderer the HTML template uses), loaded from a CDN at a pinned version.
Schema files the document references are carried along under `x-schemas`
with their references rewritten to point there, so each schema appears once
instead of once per use; example files are inlined.

The output depends only on the contract sources, so a test regenerates it and
fails when a checked-in page is stale. Run it from `v2/` after changing a
contract:

    uv run python packages/contracts/tooling/reference.py

`--bundle` also writes each self-contained document to
`dist/{service}/asyncapi.json` for tools that want one file.
"""

from __future__ import annotations

import html
import json
import sys
from pathlib import Path
from typing import Any

from openengine.contracts.validate import CONTRACTS, SERVICES, _load

RENDERER = "https://cdn.jsdelivr.net/npm/@asyncapi/react-component@3.2.1"
NAMES = {
    "connection_bus": ("Connection Bus", "cxn"),
    "graph_engine": ("Graph Engine", "ge"),
    "tool_service": ("Tool Service", "tools"),
    "virtual_control_plane": ("Virtual Control Plane", "vcp"),
}
# Where each service's subjects live: `oe.v1.{short}.` unless listed here.
NAMESPACES = {
    "tool_service": ("oe.v1.tools.", "oe.v1.toolgrants.", "oe.v1.toolinvocations.", "oe.v1.events.toolinvocations."),
}


def namespaces(service: str) -> tuple[str, ...]:
    """The subject prefixes a service's contract uses."""
    return NAMESPACES.get(service, (f"oe.v1.{NAMES[service][1]}.",))


def _key(path: Path) -> str:
    """`common/v1/command.schema.json` -> `common.v1.command`."""
    return ".".join(path.relative_to(CONTRACTS).with_suffix("").with_suffix("").parts)


def self_contained(service: str) -> dict[str, Any]:
    """The service's AsyncAPI document with every file reference resolved inside it."""
    document_path = CONTRACTS / service / "v1" / "asyncapi.yaml"
    schemas: dict[str, Any] = {}

    def rewrite(node: Any, base: Path, home: str | None = None) -> Any:
        """`home` is the `x-schemas` key of the schema file `node` came from; None for the document."""
        if isinstance(node, list):
            return [rewrite(item, base, home) for item in node]
        if not isinstance(node, dict):
            return node
        ref = node.get("$ref")
        if isinstance(ref, str) and ref.startswith("#") and home is not None:
            return {"$ref": f"#/x-schemas/{home}{ref[1:]}"}
        if isinstance(ref, str) and not ref.startswith("#"):
            file, _, pointer = ref.partition("#")
            target = (base / file).resolve()
            if "/examples/" in target.as_posix():
                value: Any = _load(target)
                for part in filter(None, pointer.split("/")):
                    value = value[part]
                return value
            key = _key(target)
            if key not in schemas:
                schemas[key] = None  # reserve before recursing, in case files refer to each other
                schemas[key] = rewrite(_load(target), target.parent, key)
            return {"$ref": f"#/x-schemas/{key}{pointer}"}
        return {name: rewrite(value, base, home) for name, value in node.items()}

    document = rewrite(_load(document_path), document_path.parent)
    document["x-schemas"] = dict(sorted(schemas.items()))
    return document


def page(service: str) -> str:
    name, short = NAMES[service]
    contract = json.dumps(self_contained(service), separators=(",", ":"), ensure_ascii=False).replace("</", "<\\/")
    title = html.escape(f"{name} contract")
    return f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{title}</title>
<!-- Generated by packages/contracts/tooling/reference.py from {service}/v1/asyncapi.yaml. Do not edit. -->
<link rel="stylesheet" href="{RENDERER}/styles/default.min.css">
<style>
  body {{ margin: 0; background: #fff; color: #1c2330; font: 14px/1.5 system-ui, sans-serif; }}
  .banner {{ display: flex; flex-wrap: wrap; gap: 4px 16px; align-items: baseline; padding: 10px 16px;
             border-bottom: 1px solid #dfe3ea; color: #5b6577; font-size: 13px; }}
  .banner strong {{ color: #1c2330; font-size: 14px; }}
  .banner code {{ background: #eef2f8; color: #1c2330; padding: 1px 6px; border-radius: 4px; }}
</style>
</head>
<body>
<header class="banner">
  <strong>{html.escape(name)} ({short})</strong>
  <span>Subjects {" ".join(f"<code>{prefix}…</code>" for prefix in namespaces(service))}</span>
  <span>Contract only: no service implements these subjects yet.</span>
</header>
<main id="contract-reference"></main>
<script id="contract" type="application/json">{contract}</script>
<script src="{RENDERER}/browser/standalone/index.js"></script>
<script>
  AsyncApiStandalone.render({{
    schema: JSON.parse(document.getElementById("contract").textContent),
    config: {{ show: {{ sidebar: true, errors: true }} }},
  }}, document.getElementById("contract-reference"));
</script>
</body>
</html>
"""


def reference_path(service: str) -> Path:
    return CONTRACTS / service / "v1" / "reference.html"


def main() -> int:
    for service in SERVICES:
        reference_path(service).write_text(page(service))
        print(f"wrote {reference_path(service).relative_to(CONTRACTS)}")
        if "--bundle" in sys.argv[1:]:
            bundle = CONTRACTS / "dist" / service / "asyncapi.json"
            bundle.parent.mkdir(parents=True, exist_ok=True)
            bundle.write_text(json.dumps(self_contained(service), indent=2, ensure_ascii=False) + "\n")
            print(f"wrote {bundle.relative_to(CONTRACTS)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
