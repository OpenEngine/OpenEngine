"""Writes `v2/docs/architecture.mermaid`, the V2 architecture, from the contracts and the migrations.

Each service is drawn with its NATS subjects, taken from its AsyncAPI document
and grouped as control, query and events, and with its tables and their
foreign keys, taken from its migrated schema. The NATS streams come from
`infra/nats/streams`, and a workspace's isolation levels from the VCP
capabilities schema. Who calls what (apps, integrations, the workspace daemon)
is not in any of those, so it is written here.

The v2 schema workflow runs this whenever a contract or a migration changes,
renders `architecture.svg` beside it and commits both. Run from `v2/`:

    uv run python packages/contracts/tooling/architecture.py [--manifest FILE]

`--manifest` adds the changed paths to an existing JSON list (the one the
schema documentation writes), so the workflow renders and commits them.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from collections.abc import Mapping, Sequence
from functools import cache
from pathlib import Path
from typing import Any

from openengine.persistence import documentation

from openengine.contracts.reference import NAMES
from openengine.contracts.validate import CONTRACTS, SERVICES, _load, load_contract

V2 = Path(__file__).resolve().parents[3]
OUTPUT = V2 / "docs" / "architecture.mermaid"
STREAMS = V2 / "infra" / "nats" / "streams"
GROUPS = ("control", "query", "events")


def subjects(service: str) -> dict[str, list[str]]:
    """The service's subject templates by group, from its operations' `control`, `query` or `event` tag."""
    document = load_contract(service).document
    grouped: dict[str, list[str]] = {group: [] for group in GROUPS}
    for operation in document["operations"].values():
        address = document["channels"][operation["channel"]["$ref"].rsplit("/", 1)[-1]]["address"]
        group = {"event": "events"}.get(operation["tags"][0]["name"], operation["tags"][0]["name"])
        if address not in grouped[group]:
            grouped[group].append(address)
    return grouped


def _prefix(addresses: Sequence[str]) -> str:
    """The subject tokens every address starts with, ending in a `.`."""
    common = addresses[0].split(".")[:-1]
    for address in addresses[1:]:
        tokens = address.split(".")
        while tokens[: len(common)] != common:
            common.pop()
    return ".".join(common) + "."


def _captures(pattern: str, subject: str) -> bool:
    """Whether a NATS stream subject filter captures a subject template."""
    tokens = subject.split(".")
    for index, part in enumerate(pattern.split(".")):
        if part == ">":
            return len(tokens) > index
        if index >= len(tokens) or part not in ("*", tokens[index]):
            return False
    return len(pattern.split(".")) == len(tokens)


def streams() -> list[tuple[str, list[str]]]:
    return [(stream["name"], stream["subjects"]) for stream in map(_load, sorted(STREAMS.glob("*.json")))]


@cache
def _persistence() -> Mapping[str, Any]:
    return {p.name: p for p in documentation.discover(V2 / "services")}


def tables(short: str) -> documentation.Tables:
    """The service's tables at its latest migration revision."""
    persistence = _persistence().get(short)
    history = documentation.snapshots(persistence) if persistence else []
    return history[-1].tables if history else {}


def comments(short: str) -> dict[str, str]:
    """The service's table comments, from its schema module."""
    persistence = _persistence().get(short)
    return documentation.comments(persistence) if persistence else {}


def _vcp_schema(name: str) -> Any:
    return _load(CONTRACTS / "virtual_control_plane" / "v1" / "schemas" / name)


def isolation_levels() -> list[str]:
    capabilities = _vcp_schema("capabilities.schema.json")
    return next(
        definition["properties"]["isolation"]["enum"]
        for definition in capabilities["$defs"].values()
        if "isolation" in definition.get("properties", {})
    )


def providers() -> list[str]:
    """The example providers the workspace schema names."""
    return re.findall(r"`([a-z0-9_-]+)`", _vcp_schema("workspace.schema.json")["$defs"]["provider"]["description"])


def _label(*lines: str) -> str:
    text = "<br/>".join(lines).replace('"', "#quot;")
    return f'"{text}"'


def _subject_lines(prefix: str, addresses: Sequence[str]) -> list[str]:
    return [f"<b>{prefix}</b>", *(address.removeprefix(prefix) for address in addresses)]


def diagram() -> str:
    all_streams = streams()
    lines = [
        "---",
        "title: OpenEngine V2 architecture",
        "config:",
        "  theme: neutral",
        "  flowchart:",
        "    htmlLabels: true",
        "    wrappingWidth: 600",
        "---",
        "%% Generated by packages/contracts/tooling/architecture.py from the service contracts,",
        "%% their migrations and infra/nats/streams. Do not edit.",
        "flowchart LR",
        "    classDef app fill:#e0e7ff,stroke:#4338ca,color:#1e1b4b",
        "    classDef integration fill:#fce7f3,stroke:#be185d,color:#500724",
        "    classDef subjects fill:#f8fafc,stroke:#64748b,color:#0f172a,text-align:left",
        "    classDef stream fill:#fef3c7,stroke:#b45309,color:#78350f",
        "    classDef table fill:#dcfce7,stroke:#15803d,color:#14532d",
        "    classDef runtime fill:#f1f5f9,stroke:#334155,color:#0f172a",
        "",
        '    subgraph apps["Apps"]',
        '        cli["oe CLI"]',
        '        supervisor["supervisor (oe up)"]',
        "    end",
        '    subgraph integrations["Integrations"]',
        '        github["GitHub"]',
        '        slack["Slack"]',
        "    end",
        "    class cli,supervisor app",
        "    class github,slack integration",
        '    nats[("NATS server")]',
        "    class nats stream",
    ]
    for service in SERVICES:
        name, short = NAMES[service]
        grouped = subjects(service)
        drawn: set[str] = set()
        lines.append(f'    subgraph {short}["{name} ({short})"]')
        for group in GROUPS:
            if not grouped[group]:
                continue
            prefix = _prefix(grouped[group])
            stream = next(
                (s for s, patterns in all_streams if any(_captures(p, grouped[group][0]) for p in patterns)), None
            )
            drawn.add(stream or "")
            heading = [f"NATS {group}{f' → stream {stream}' if stream else ''}"]
            node = f"{short}_{group}"
            lines.append(f"        {node}[{_label(*heading, *_subject_lines(prefix, grouped[group]))}]")
            lines.append(f"        class {node} subjects")
        # Streams the contracts do not cover, such as provider traffic.
        for stream, patterns in all_streams:
            if stream.startswith(f"{short}-") and stream not in drawn:
                node = stream.replace("-", "_")
                lines.append(f"        {node}[({_label(f'stream {stream}', *patterns)})]")
                lines.append(f"        class {node} stream")
        schema = tables(short)
        table_comments = comments(short)
        lines.append(f'        subgraph {short}_db["database {short}"]')
        for table in sorted(schema) or ["(no tables)"]:
            label = _label(table, table_comments[table]) if table_comments.get(table) else _label(table)
            lines.append(f"            {short}_t_{re.sub(r'[^a-z0-9_]', '_', table)}[({label})]")
            lines.append(f"            class {short}_t_{re.sub(r'[^a-z0-9_]', '_', table)} table")
        for table, definition in sorted(schema.items()):
            for foreign_key in definition["foreign_keys"]:
                lines.append(f"            {short}_t_{foreign_key['referred_table']} --- {short}_t_{table}")
        lines.append("        end")
        lines.append("    end")

    levels = " · ".join(isolation_levels())
    examples = ", ".join(providers())
    lines += [
        "",
        '    subgraph virtualization["Virtualization"]',
        "        direction TB",
        f'        provider[{_label("workspace provider", f"such as {examples}")}]',
        f'        subgraph runtime[{_label("runtime, generation n", f"isolation: {levels}")}]',
        "            direction TB",
        '            daemon["workspace daemon"]',
        '            sessions["agent sessions and task attempts"]',
        '            checkout[("workspace checkout")]',
        "            daemon --> sessions --> checkout",
        "        end",
        "        restored[" + _label("runtime, generation n+1", "restored from a checkpoint") + "]",
        '        provider -- "provisions" --> runtime',
        '        runtime -. "suspend, restore" .-> restored',
        "    end",
        "    class provider,daemon,sessions,checkout,restored runtime",
        "",
        "    %% Who calls what.",
        "    cli --> ge_control & ge_query",
        '    cli -- "connections" --> cxn_control & cxn_query',
        '    supervisor -. "starts" .-> nats',
    ]
    for integration in ("github", "slack"):
        lines.append(f'    {integration} -- "webhooks" --> cxn_ingress')
        # Undirected, so the integrations rank with the apps, left of cxn; the label gives the direction.
        lines.append(f'    {integration} --- |"← API calls"| cxn_egress')
    lines += [
        '    cxn -- "jobs" --> ge_control',
        '    ge -- "workspaces" --> vcp_control',
        '    vcp_events -. "workspace and task events" .-> ge',
        '    vcp -- "provision, suspend, restore" --> provider',
        '    vcp -- "execute, steer, cancel" --> daemon',
        # Undirected from the tool service, so it ranks beside VCP rather than after the runtime.
        '    tools_control --- |"← invoke tools"| sessions',
        '    ge -- "tool grants" --> tools_control',
        # Undirected from cxn, so cxn stays left of the tool service; the label gives the direction.
        '    cxn_query --- |"read by tools"| tools',
    ]
    return "\n".join(lines) + "\n"


def write(manifest: Path | None) -> bool:
    """Write the diagram if it changed or its SVG is missing; add both to `manifest`."""
    content = diagram()
    svg = OUTPUT.with_suffix(".svg")
    changed = not (OUTPUT.exists() and OUTPUT.read_text() == content and svg.exists())
    if changed:
        OUTPUT.write_text(content)
    if manifest and changed:
        paths = json.loads(manifest.read_text()) if manifest.exists() else []
        root = V2.parent
        paths += [str(OUTPUT.relative_to(root)), str(svg.relative_to(root))]
        manifest.write_text(json.dumps(sorted(set(paths))))
    return changed


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--manifest", type=Path, help="add the changed paths to this JSON list")
    arguments = parser.parse_args(argv)
    changed = write(arguments.manifest)
    print(f"{'wrote' if changed else 'unchanged'} {OUTPUT.relative_to(V2)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
