"""Generate the current first-party package dependency diagram from manifests."""
from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import tomllib


ROOT = Path(__file__).resolve().parents[1]


def normalize(name: str) -> str:
    return re.sub(r'[-_.]+', '-', name).lower()


def packages(root: Path) -> dict:
    manifests = [root / 'pyproject.toml']
    for folder in ('packages', 'apps', 'cli', 'langgraph-acp', 'npm', 'site', 'e2e'):
        for directory, children, files in os.walk(root / folder):
            children[:] = sorted(child for child in children if not child.startswith('.')
                                 and child not in {'node_modules', 'dist', 'build', '__pycache__'})
            manifests.extend(Path(directory) / name for name in ('pyproject.toml', 'package.json')
                             if name in files)
    result = {}
    for manifest in sorted(manifests):
        if not manifest.exists():
            continue
        python = manifest.suffix == '.toml'
        data = (tomllib.loads(manifest.read_text()).get('project', {}) if python
                else json.loads(manifest.read_text()))
        if 'name' not in data:
            continue
        dependencies = data.get('dependencies', [])
        optional = (sum(data.get('optional-dependencies', {}).values(), []) if python
                    else list(data.get('optionalDependencies', {})))
        def names(values):
            if not python:
                return sorted(values)
            return sorted({normalize(re.match(r'[A-Za-z0-9_.-]+', value).group())
                           for value in values})
        key = ('python:' + normalize(data['name']) if python else 'npm:' + data['name'])
        result[key] = {'name': data['name'], 'path': manifest.parent.relative_to(root).as_posix(),
                       'dependencies': names(dependencies), 'optional': names(optional)}
    return result


def diagram(current: dict) -> str:
    lines = ['---', 'title: First-party package dependencies', 'config:', '  theme: neutral',
             '---', 'flowchart LR',
             '    %% Generated by scripts/package_diagram.py; do not edit.',
             '    %% Arrows: package -> declared dependency; dashed: optional dependency.',
             '    %% External and development dependencies are omitted; markers are not evaluated.']
    ids = {key: 'p' + hashlib.sha256(key.encode()).hexdigest()[:12] for key in current}
    for key, package in sorted(current.items()):
        label = f'{package["name"]}<br/>{package["path"]}'
        label = label.replace('&', '&amp;').replace('"', '&quot;')
        lines.append(f'    {ids[key]}["{label}"]')
    for key, package in sorted(current.items()):
        ecosystem = key.split(':', 1)[0]
        for field, arrow in (('dependencies', '-->'), ('optional', '-.->')):
            for dependency in package[field]:
                target = f'{ecosystem}:{dependency}'
                if target in ids:
                    lines.append(f'    {ids[key]} {arrow} {ids[target]}')
    return '\n'.join(lines) + '\n'


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, default=ROOT)
    parser.add_argument('--output', type=Path, default=Path('docs/architecture'))
    parser.add_argument('--manifest', type=Path, default=Path('package-changes.json'))
    args = parser.parse_args()
    content = diagram(packages(args.root))
    target, png = args.output / 'packages.mermaid', args.output / 'packages.png'
    changed = not target.exists() or target.read_text() != content or not png.exists()
    if changed:
        args.output.mkdir(parents=True, exist_ok=True)
        target.write_text(content)
    args.manifest.write_text(json.dumps([str(target), str(png)] if changed else []))


if __name__ == '__main__':
    main()
